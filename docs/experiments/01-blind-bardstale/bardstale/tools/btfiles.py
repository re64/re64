#!/usr/bin/env python3
"""Bard's Tale C64 file knowledge shared by tools.

Load-address rule (resident loader $78B9..$7906, table D_796C at $796C):
  file# < $50 : page = D_796C[file#]
  $50..$9F    : $C000  (pictures)
  $A0..$EF    : $F800  (dungeon maps, under KERNAL ROM)
  $F0         : $BB00
"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

_D796C = [0xC0,0xC0,0xAE,0xAE,0xE0,0xE0,0xE0,0xE0,0xE0,0xAE,0xC0] + [0xB6]*17 + [0xBB]*52
assert len(_D796C) == 0x50

def load_page(n):
    if n < 0x50: return _D796C[n]
    if n == 0xF0: return 0xBB
    if n < 0xA0: return 0xC0
    return 0xF8

def load_addr(n): return load_page(n) << 8

# which disk holds which file (from directory listings)
DISK1 = set([0x00,0x01,0x03,0x04,0x09,0x0A,0x0B,0x0C,0x0D,0x0E,0x0F,0x10,0x11,0x12,0x13,0x14,0x15,0x16,0x17,0x18,0x19,0x1A,0x1B,
             0x50,0x51,0x52,0x53,0x54,0x55,0x56,0x57,0x58,0x59,0x5A,0x5B,0x5C,0x5D,0x5E,0x5F,0x60,0x61,0x62,0x63,0x64,0x65,0x66,0x67,0x68,0x69,0x6A,0x6B,0x6C,0x6D,0x6E,0x6F,0x70,0x71,0x72,0x74,0x75,0x76,0x7A,0x7D,0x7F,
             0x80,0x81,0x82,0x83,0x84,0x85,0x86,0x87,0x88,0x89,0x8A,0x8B,0x8C,0x8D,0x8E,0x8F,0x90,0xF0])
DISK2 = set([0x02,0x05,0x06,0x07,0x08]+list(range(0x1C,0x45))+list(range(0x5E,0x75))+[0x77,0x78,0x79,0x7B,0x7C,0x7D,0x7E,0x7F,0x80,0x81,0x82]+list(range(0xA0,0xB0)))

# mode -> main overlay (D_1A5F): 0=city NM09 (+NM04 data), 1=dungeon NM02, 2=NM03
MODE_OVERLAY = {0: 0x09, 1: 0x02, 2: 0x03}
# special-location type (0..31) -> overlay (D_1B28); type 6 = enter dungeon
SPECIAL_OVERLAY = [0x00,0x1B,0x0C,0x0D,0x0E,0x0B,None,0x0F,0x10,0x1C,0x1D,0x1E,0x11,0x12,0x14,0x13,
                   0x1F,0x20,0x21,0x22,0x23,0x24,0x25,0x15,0x26,0x27,0x28,0x29,0x2A,0x2B,0x2C,0x2D]
# 10 pictures kept resident under ROM (D_7962 / D_0D85 / D_0D8F)
RESIDENT_PICS = {0x5A:(0xED00,2),0x5B:(0xEF00,2),0x5C:(0xF100,2),0x5D:(0xF300,3),0x8B:(0xD000,2),0x8C:(0xD200,2),
                 0x8D:(0xD400,2),0x8E:(0xD600,2),0x57:(0xD800,3),0x53:(0xDB00,2)}

def file_path(n):
    name = f"nm{n:02x}.prg"
    for d in ('d1', 'd2'):
        p = os.path.join(ROOT, 'extracted', d, name)
        if os.path.exists(p): return p
    raise FileNotFoundError(name)

def file_body(n):
    return open(file_path(n), 'rb').read()[2:]

def resident_mem():
    return bytearray(open(os.path.join(ROOT, 'extracted', 'd1', 'main.mem'), 'rb').read())

def build_mem(files=(), base=None):
    """Return a 64K bytearray: resident image + given files at their real load addresses."""
    mem = base if base is not None else resident_mem()
    for n in files:
        b = file_body(n); a = load_addr(n)
        mem[a:a+len(b)] = b
    return mem

if __name__ == '__main__':
    for n in sorted(DISK1 | DISK2):
        b = file_body(n); a = load_addr(n)
        print(f"NM{n:02X}  disk={'1' if n in DISK1 else ''}{'2' if n in DISK2 else ''}  ${a:04X}-${a+len(b)-1:04X}  {len(b):5d} bytes")
